'use strict';
// Assertions inspect the actual Compose merge, not YAML source text.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = process.argv[2];
const read = name => JSON.parse(fs.readFileSync(path.join(root, name + '.json'), 'utf8'));
const base = read('base'), merged = read('merged'), restore = read('restore');
const names = service => new Set((service.secrets || []).map(item => item.source));
const has = (set, list) => list.forEach(item => assert.ok(set.has(item), item));
const web = base.services.web, maintenance = base.services.maintenance;
assert.equal(web.environment.HOMEPLANNER_MAIL_ENABLED, '0');
assert.equal(web.environment.HOMEPLANNER_TRUSTED_PROXY_IP, '');
assert.ok(!names(web).has('gmail_app_password'));
has(names(web), ['access_public_database_url', 'mail_database_url', 'access_rate_key']);
has(names(maintenance), ['access_public_db_password', 'mail_db_password', 'migration_database_url']);
for (const name of ['migration_database_url', 'access_public_db_password', 'mail_db_password']) assert.ok(!names(web).has(name));
assert.equal(web.environment.HOMEPLANNER_ACCESS_PUBLIC_DATABASE_URL_FILE, '/run/secrets/access_public_database_url');
assert.equal(web.environment.HOMEPLANNER_MAIL_DATABASE_URL_FILE, '/run/secrets/mail_database_url');
assert.equal(web.environment.HOMEPLANNER_ACCESS_RATE_KEY_FILE, '/run/secrets/access_rate_key');
assert.equal(maintenance.environment.HOMEPLANNER_ACCESS_PUBLIC_DB_PASSWORD_FILE, '/run/secrets/access_public_db_password');
assert.equal(maintenance.environment.HOMEPLANNER_MAIL_DB_PASSWORD_FILE, '/run/secrets/mail_db_password');
assert.ok(maintenance.volumes.some(v => v.target === '/run/homeplanner-operations.lock' && v.read_only));
assert.equal(web.image, maintenance.image);
assert.equal(web.image, process.argv[3]);
const live = merged.services.web;
assert.equal(live.environment.HOMEPLANNER_MAIL_ENABLED, '1');
assert.equal(live.environment.HOMEPLANNER_TRUSTED_PROXY_IP, '192.0.2.10');
assert.equal(live.environment.HOMEPLANNER_GMAIL_APP_PASSWORD_FILE, '/run/secrets/gmail_app_password');
has(names(live), ['gmail_app_password', 'provider_api_key', 'access_rate_key', 'auth_secret']);
assert.deepEqual(live.ports || [], []);
for (const network of ['database', 'outbound', 'ingress']) assert.ok(Object.hasOwn(live.networks, network));
assert.ok(live.networks.ingress.aliases.includes('homeplanner-web'));
assert.equal(merged.networks.ingress.name, 'homeplanner_ingress');
assert.equal(merged.networks.ingress.external, true);
assert.deepEqual(merged.services.db, base.services.db);
has(names(restore.services.maintenance), ['access_public_password', 'mail_password']);
assert.ok(restore.networks.isolated.internal);
assert.equal(restore.services.maintenance.image, process.argv[3]);
console.log('PASS actual base, mail/ingress/provider merged, and isolated restore Compose configurations');
